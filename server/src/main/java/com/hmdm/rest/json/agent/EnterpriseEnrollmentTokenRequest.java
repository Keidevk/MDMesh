package com.hmdm.rest.json.agent;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import io.swagger.annotations.ApiModel;
import io.swagger.annotations.ApiModelProperty;

import java.io.Serializable;

@ApiModel(description = "Request to create enterprise enrollment token")
@JsonIgnoreProperties(ignoreUnknown = true)
public class EnterpriseEnrollmentTokenRequest implements Serializable {

    private static final long serialVersionUID = 1L;

    @ApiModelProperty("Configuration ID to bind the enrolled device to (optional)")
    private Integer configurationId;

    @ApiModelProperty("Whether token is single-use (default: true)")
    private Boolean oneTime = true;

    @ApiModelProperty("Token validity duration in milliseconds (default: 86400000 = 24h, max 30 days)")
    private Long durationMillis = 86400000L;

    public EnterpriseEnrollmentTokenRequest() {
    }

    public Integer getConfigurationId() {
        return configurationId;
    }

    public void setConfigurationId(Integer configurationId) {
        this.configurationId = configurationId;
    }

    public Boolean getOneTime() {
        return oneTime;
    }

    public void setOneTime(Boolean oneTime) {
        this.oneTime = oneTime;
    }

    public Long getDurationMillis() {
        return durationMillis;
    }

    public void setDurationMillis(Long durationMillis) {
        this.durationMillis = durationMillis;
    }
}